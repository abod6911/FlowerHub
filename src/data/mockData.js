// Helper: Generate Injected CSS Variables from Studio State
export const generateCssVariables = (studioState) => {
  if (!studioState) return {};
  const opacityHex = Math.round((studioState.glassOpacity ?? 0.9) * 255).toString(16).padStart(2, '0');
  const surfaceWithAlpha = studioState.glassEffect
    ? `${studioState.surfaceBg}${opacityHex}`
    : studioState.surfaceBg;

  return {
    '--bg-canvas': studioState.canvasBg,
    '--surface-card': studioState.surfaceBg,
    '--surface-glass': surfaceWithAlpha,
    '--accent-primary': studioState.accentPrimary,
    '--accent-gold': studioState.goldAccent,
    '--text-main': studioState.textPrimary,
    '--text-muted': studioState.textMuted,
    '--border-subtle': studioState.surfaceBorder,
    '--radius-unit': studioState.radiusCard || '16px',
    '--radius-btn': studioState.radiusButton || '9999px',
    '--glass-blur': studioState.glassEffect ? studioState.glassBlur : '0px',
    '--ease-transition':
      studioState.motionPreset === 'snappy'
        ? 'cubic-bezier(0.4, 0, 0.2, 1)'
        : studioState.motionPreset === 'springy'
        ? 'cubic-bezier(0.34, 1.56, 0.64, 1)'
        : 'cubic-bezier(0.16, 1, 0.3, 1)',
    // Backwards compatibility mappings
    '--canvas-bg': studioState.canvasBg,
    '--surface-bg': surfaceWithAlpha,
    '--surface-border': studioState.surfaceBorder,
    '--text-primary': studioState.textPrimary,
    '--gold-accent': studioState.goldAccent,
    '--radius-card': studioState.radiusCard || '16px',
    '--anim-duration':
      studioState.motionPreset === 'snappy' ? '0.18s' : studioState.motionPreset === 'springy' ? '0.4s' : '0.3s',
  };
};

