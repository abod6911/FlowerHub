// Formats a clean structured WhatsApp message ticket scannable in 3 seconds
export function generateWhatsAppMessage({
  shopConfig = null,
  lang = 'ar',
  items = [],
  handover = { type: 'pickup', timing: 'الآن / مستعجل' },
  customOrder = null,
  trustPhoto = true,
  orderId = '8492',
}) {
  const isAr = lang === 'ar';
  const divider = '━━━━━━━━━━━━━━━━━━━━━━';
  const cleanId = String(orderId).replace('FLW-', '').replace('#', '');
  const orderUrl = `https://flowerhub.sa/o/${cleanId || '8492'}`;

  const shopName = isAr
    ? shopConfig?.shopNameAr || 'دار الورد للمناسبات'
    : shopConfig?.shopNameEn || 'Maison des Fleurs Atelier';

  const dateStr = new Date().toLocaleDateString(isAr ? 'ar-SA' : 'en-US');
  const timeStr = new Date().toLocaleTimeString(isAr ? 'ar-SA' : 'en-US', {
    hour: '2-digit',
    minute: '2-digit',
  });

  if (customOrder) {
    if (isAr) {
      return `*طلب تنسيق خاص • ${shopName}*
رقم الإيصال: #FL-${cleanId}
التاريخ: ${dateStr} • ${timeStr}
${divider}
*تفاصيل الطلب المخصص:*
• نوع الخدمة: ${customOrder.modeTitle}
• طابع الألوان المفضل: ${customOrder.colorVibe || 'ألوان باستيل كلاسيكية'}
• الميزانية التقريبية: ${customOrder.budget || '٢٥٠ ر.س تقريباً'}
${customOrder.hasPhoto ? '• تم إرفاق صورة مرجعية للتنفيذ ✓' : ''}
${customOrder.notes ? `• ملاحظات وتفضيلات خاصة: "${customOrder.notes}"` : ''}

${divider}
*طريقة وموعد الاستلام:*
${formatHandoverText(handover, true)}

${trustPhoto ? '• الرجاء إرسال صورة الباقة للاعتماد قبل انطلاق المندوب ✓' : ''}
${divider}
📄 رابط إيصال الطلب الرقمي:
${orderUrl}

أهلاً وسهلاً فريق ${shopName}، أود تأكيد التنسيق والتفاصيل المتبقية والدفع معكم.`;
    } else {
      return `*Bespoke Floral Order • ${shopName}*
Receipt #: #FL-${cleanId}
Date: ${dateStr} • ${timeStr}
${divider}
*Custom Order Details:*
• Service: ${customOrder.modeTitle}
• Palette: ${customOrder.colorVibe || 'Classic Pastel'}
• Estimated Budget: ${customOrder.budget || '~250 SAR'}
${customOrder.hasPhoto ? '• Reference photo provided ✓' : ''}
${customOrder.notes ? `• Special Notes: "${customOrder.notes}"` : ''}

${divider}
*Handover & Timing:*
${formatHandoverText(handover, false)}

${trustPhoto ? '• Photo confirmation requested prior to dispatch ✓' : ''}
${divider}
📄 Digital Order Slip:
${orderUrl}

Hello ${shopName} team! I would like to finalize and arrange payment for this bespoke order.`;
    }
  }

  // Calculate totals
  const total = items.reduce((sum, item) => sum + (item.price || 0) * (item.quantity || 1), 0);
  const effectiveHandover = items[0]?.handover || handover;
  const deliveryCost = effectiveHandover.type === 'pickup' ? 0 : total >= 300 ? 0 : 25;
  const grandTotal = total + deliveryCost;

  if (isAr) {
    let msg = `*طلب مؤكد • ${shopName}*
رقم الإيصال: #FL-${cleanId}
التاريخ: ${dateStr} • ${timeStr}
${divider}
*الباقات والقطع المطلوبة:*
`;

    items.forEach((item, index) => {
      const title = item.titleAr || item.titleEn;
      const basePrice = item.basePrice || item.price;
      const qtyStr = item.quantity && item.quantity > 1 ? ` (${item.quantity}x)` : '';
      msg += `\n${items.length > 1 ? `${index + 1}. ` : ''}*${title}* (${basePrice} ر.س)${qtyStr}`;

      // Preparation style & Customization
      if (item.orderStyle === 'tweak' && item.modificationNote) {
        msg += `\n  • التنسيق والتغليف: تعديل خاص: "${item.modificationNote}"`;
      } else if (item.orderStyle === 'tweak') {
        msg += `\n  • التنسيق والتغليف: تعديل مخصص للألوان والتغليف`;
      } else {
        msg += `\n  • التنسيق والتغليف: مطابقة للصورة بدقة`;
      }

      // Add-ons
      if (item.addons && item.addons.length > 0) {
        const addonsList = item.addons
          .map((a) => {
            const extra = a.phrase ? ` «${a.phrase}»` : '';
            return `${a.nameAr || a.nameEn}${extra} (+${a.price} ر.س)`;
          })
          .join(' + ');
        msg += `\n  • الإضافات: ${addonsList}`;
      }

      // Gift Card Note
      const giftNote = item.giftCardMessage || item.giftCard?.message;
      if (giftNote && giftNote.trim().length > 0) {
        msg += `\n  • كرت الإهداء المطبوع: "${giftNote.trim()}"`;
      } else {
        msg += `\n  • كرت الإهداء: بدون كرت إهداء`;
      }
    });

    msg += `\n\n${divider}
*طريقة وموعد التسليم:*
${formatHandoverText(effectiveHandover, true)}

${trustPhoto ? '• إرسال صورة الباقة المنسقة للاعتماد قبل خروج المندوب ✓' : ''}
${divider}
المجموع الفرعي: ${total} ر.س
رسوم التوصيل: ${deliveryCost === 0 ? 'مجاني (عرض خاص)' : `${deliveryCost} ر.س`}
*المبلغ الإجمالي: ${grandTotal} ر.س*
${divider}
📄 رابط الإيصال وتتبع الطلب:
${orderUrl}

أهلاً وسهلاً فريق ${shopName}، أود تأكيد هذا الطلب وإتمام الدفع معكم عبر الواتساب.`;
    return msg;
  } else {
    let msg = `*Confirmed Order • ${shopName}*
Receipt #: #FL-${cleanId}
Date: ${dateStr} • ${timeStr}
${divider}
*Order Items:*
`;

    items.forEach((item, index) => {
      const title = item.titleEn || item.titleAr;
      const basePrice = item.basePrice || item.price;
      const qtyStr = item.quantity && item.quantity > 1 ? ` (${item.quantity}x)` : '';
      msg += `\n${items.length > 1 ? `${index + 1}. ` : ''}*${title}* (${basePrice} SAR)${qtyStr}`;

      // Preparation style
      if (item.orderStyle === 'tweak' && item.modificationNote) {
        msg += `\n  • Prep & Wrap: Custom tweak: "${item.modificationNote}"`;
      } else if (item.orderStyle === 'tweak') {
        msg += `\n  • Prep & Wrap: Custom color/wrapping adjustment`;
      } else {
        msg += `\n  • Prep & Wrap: Exactly as shown in photo`;
      }

      // Add-ons
      if (item.addons && item.addons.length > 0) {
        const addonsList = item.addons
          .map((a) => {
            const extra = a.phrase ? ` "${a.phrase}"` : '';
            return `${a.nameEn || a.nameAr}${extra} (+${a.price} SAR)`;
          })
          .join(' + ');
        msg += `\n  • Extras: ${addonsList}`;
      }

      // Gift Card Note
      const giftNote = item.giftCardMessage || item.giftCard?.message;
      if (giftNote && giftNote.trim().length > 0) {
        msg += `\n  • Printed Gift Note: "${giftNote.trim()}"`;
      } else {
        msg += `\n  • Printed Gift Note: None`;
      }
    });

    msg += `\n\n${divider}
*Handover & Timing:*
${formatHandoverText(effectiveHandover, false)}

${trustPhoto ? '• Photo confirmation before dispatch requested ✓' : ''}
${divider}
Subtotal: ${total} SAR
Delivery Fee: ${deliveryCost === 0 ? 'Free' : `${deliveryCost} SAR`}
*Grand Total: ${grandTotal} SAR*
${divider}
📄 Digital Receipt Link:
${orderUrl}

Hello ${shopName} team! I would like to finalize and arrange payment for my order.`;
    return msg;
  }
}

function formatHandoverText(handover, isAr) {
  const timing = handover.timing || handover.pickupTime || (isAr ? 'الآن / مستعجل' : 'Now / Urgent');
  if (handover.type === 'pickup') {
    if (isAr) {
      return `• استلام مباشر من فرع المحل (${timing})`;
    }
    return `• In-Store Pickup (${timing})`;
  } else if (handover.type === 'delivery') {
    const address = handover.address || handover.district;
    if (isAr) {
      return `• توصيل لموقعي (${timing})${address ? `\n  العنوان: ${address}` : '\n  (سأرسل موقعي GPS في المحادثة)'}`;
    }
    return `• Direct Delivery (${timing})${address ? `\n  Address: ${address}` : '\n  (Will share GPS location in chat)'}`;
  } else if (handover.type === 'gift') {
    const rName = handover.recipientName || (isAr ? 'مستلم كريم' : 'Valued Recipient');
    const rPhone = handover.recipientPhone || (isAr ? 'غير محدد' : 'Not provided');
    if (isAr) {
      return `• إهداء لمستلم آخر: ${rName} (${rPhone})
  🔒 الرجاء التواصل مع المستلم بلباقة لتحديد موعد ومكان التسليم دون حرق المفاجأة.`;
    }
    return `• Surprise Gift Delivery: ${rName} (${rPhone})
  🔒 Please discreetly coordinate delivery with the recipient without spoiling the surprise.`;
  }
  return '';
}
